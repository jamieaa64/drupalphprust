<?php
// Standalone reproduction of Simple Sitemap's inherited in-memory writer API.
class SitemapProbeWriter extends XMLWriter {
    public function __construct(public string $label) {}
}
$writer = new SitemapProbeWriter('probe');
var_dump($writer instanceof XMLWriter, $writer->label);
var_dump($writer->openMemory(), $writer->setIndent(true));
var_dump($writer->startDocument('1.0', 'UTF-8'));
var_dump($writer->writePI('xml-stylesheet', 'type="text/xsl" href="/sitemap.xsl"'));
var_dump($writer->writeComment('Generated by a standalone compatibility probe.'));
var_dump($writer->startElement('urlset'));
var_dump($writer->writeAttribute('xmlns', 'http://www.sitemaps.org/schemas/sitemap/0.9'));
var_dump($writer->writeAttribute('xmlns:xhtml', 'http://www.w3.org/1999/xhtml'));
var_dump($writer->startElement('url'));
var_dump($writer->writeElement('loc', 'https://example.test/?a=1&b=<two>'));
var_dump($writer->writeElement('lastmod', '2026-11-12T00:00:00+00:00'));
var_dump($writer->startElement('xhtml:link'));
var_dump($writer->writeAttribute('href', 'https://example.test/"quoted"?a=1&b=2'));
var_dump($writer->writeAttribute('hreflang', 'fr'));
var_dump($writer->endElement(), $writer->endElement(), $writer->endElement());
var_dump($writer->endDocument());
$snapshot = $writer->outputMemory(false);
echo $snapshot;
var_dump($snapshot === $writer->outputMemory(), $writer->outputMemory());
// A new memory writer resets prior state and preserves UTF-8 bytes.
var_dump($writer->openMemory());
$writer->startElement('root');
$writer->writeElement('empty');
$writer->writeElement('text', 'café & < > "');
$writer->endElement();
echo $writer->outputMemory(), "\n";
